#!/usr/bin/env python3
"""Render the repeatable campus seed from its one catalogue source."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'backend/catalogue/campus-items.json'
OUTPUT = ROOT / 'backend/crates/loan-service/migrations/demo_seed.sql'
OLD_DESCRIPTIONS = {
    'dell-latitude-7440': '14-inch business laptop with 16 GB RAM and USB-C dock support for 2-day campus loans.',
    'macbook-air-m3': '13-inch macOS laptop for mobile development and media coursework (2-day loan).',
    'ipad-air-m2': 'Tablet kit for design and annotation studio sessions (2-day loan).',
    'sony-alpha-a6400': 'Mirrorless camera with 16-50mm lens and SD card for media production (2-day loan).',
}

def quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def render(items):
    assert len(items) == 36 and len({i['id'] for i in items}) == 36
    unit_ids = [u['unitId'] for i in items for u in i['units']]
    assert len(set(unit_ids)) == len(unit_ids)
    for item in items:
        assert item['loanDurationDays'] == 14
        assert 3 <= len(item['specifications']) <= 6
        assert all(s['label'] and s['value'] for s in item['specifications'])
        assert item['imageUrl'] == f"/catalogue/{item['id']}.webp"
        for unit in item['units']:
            assert unit['status'] in ['AVAILABLE', 'MAINTENANCE']
    model_data = [{
        'id': i['id'], 'name': i['name'], 'category': i['category'],
        'description': i['description'], 'image_url': i['imageUrl'], 'image_alt': i['imageAlt'],
        'specifications': i['specifications'],
        'original_description': OLD_DESCRIPTIONS.get(i['id'], i['description'])
    } for i in items]
    unit_data = [{'unit_id': u['unitId'], 'model_id': i['id'], 'serial_number': u['serialNumber'], 'status': u['status']} for i in items for u in i['units']]
    model_rows = "SELECT * FROM jsonb_to_recordset(seed_models) AS m(id TEXT, name TEXT, category TEXT, description TEXT, image_url TEXT, image_alt TEXT, specifications JSONB, original_description TEXT)"
    unit_rows = "SELECT * FROM jsonb_to_recordset(seed_units) AS u(unit_id TEXT, model_id TEXT, serial_number TEXT, status TEXT)"
    return f"""-- Generated by scripts/catalogue.py; edit backend/catalogue/campus-items.json.
-- Runs in the migration transaction; needs no database CREATE or TEMP privilege.
DO $campus$
DECLARE
    seed_models JSONB := {quote(json.dumps(model_data, ensure_ascii=False))};
    seed_units JSONB := {quote(json.dumps(unit_data, ensure_ascii=False))};
    conflict_id TEXT;
BEGIN
    WITH campus_seed_models AS ({model_rows}), campus_seed_units AS ({unit_rows}),
    new_models AS (
        INSERT INTO loan.device_models (id, name, category, description, loan_duration_days,
            total_units, available_units, image_url, image_alt, specifications, updated_at)
        SELECT m.id, m.name, m.category, m.description, 14,
            (SELECT count(*) FROM campus_seed_units u WHERE u.model_id = m.id),
            (SELECT count(*) FROM campus_seed_units u WHERE u.model_id = m.id AND u.status = 'AVAILABLE'),
            m.image_url, m.image_alt, m.specifications, NOW()
        FROM campus_seed_models m
        ON CONFLICT (id) DO NOTHING RETURNING id
    )
    INSERT INTO loan.device_units (unit_id, model_id, serial_number, status, updated_at)
    SELECT u.unit_id, u.model_id, u.serial_number, u.status, NOW()
    FROM campus_seed_units u JOIN new_models m ON m.id = u.model_id;

    WITH campus_seed_models AS ({model_rows})
    UPDATE loan.device_models d SET
        description = m.description,
        image_url = COALESCE(d.image_url, m.image_url),
        image_alt = COALESCE(d.image_alt, m.image_alt),
        specifications = CASE WHEN d.specifications = '[]'::jsonb THEN m.specifications ELSE d.specifications END,
        updated_at = NOW()
    FROM campus_seed_models m WHERE d.id = m.id
        AND d.description IN (m.original_description, m.description)
        AND (d.description <> m.description OR d.image_url IS NULL OR d.image_alt IS NULL OR d.specifications = '[]'::jsonb);

    FOR conflict_id IN
        WITH campus_seed_models AS ({model_rows})
        SELECT d.id FROM loan.device_models d JOIN campus_seed_models m ON m.id = d.id
        WHERE d.description NOT IN (m.original_description, m.description)
    LOOP
        RAISE WARNING 'Catalogue seed preserved edited description and metadata for %; review specs manually', conflict_id;
    END LOOP;
END $campus$;
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render(json.loads(SOURCE.read_text()))
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit('Catalogue seed is stale: run python3 scripts/catalogue.py')
        items = json.loads(SOURCE.read_text())
        credits = json.loads((ROOT / 'frontend/public/catalogue/sources.json').read_text())
        assert {c['id'] for c in credits} == {i['id'] for i in items}
        assert len(credits) == 36
        assert all(c['sourceUrl'] and c['licence'] and c['licenceUrl'] and c['author'] for c in credits)
        for item in items:
            asset = ROOT / 'frontend/public' / item['imageUrl'].lstrip('/')
            if not asset.is_file() or asset.read_bytes()[:4] != b'RIFF':
                raise SystemExit(f'Missing catalogue image: {asset}')
        print('Catalogue: 36 models, seed current, all images present')
    else:
        OUTPUT.write_text(expected)


if __name__ == '__main__':
    main()
